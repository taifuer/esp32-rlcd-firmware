size_t weather_location_province_count(void)
{
    return WEATHER_LOCATION_PROVINCE_COUNT;
}

const weather_province_t *weather_location_province_at(size_t index)
{
    if (index >= WEATHER_LOCATION_PROVINCE_COUNT) {
        return NULL;
    }
    return &k_provinces[index].value;
}

static const province_record_t *find_province(
    weather_province_id_t province_id)
{
    size_t low = 0U;
    size_t high = WEATHER_LOCATION_PROVINCE_COUNT;
    while (low < high) {
        const size_t middle = low + (high - low) / 2U;
        const weather_province_id_t candidate =
            k_provinces[middle].value.id;
        if (candidate < province_id) {
            low = middle + 1U;
        } else {
            high = middle;
        }
    }
    if (low >= WEATHER_LOCATION_PROVINCE_COUNT ||
        k_provinces[low].value.id != province_id) {
        return NULL;
    }
    return &k_provinces[low];
}

const weather_province_t *weather_location_province_by_id(
    weather_province_id_t province_id)
{
    const province_record_t *province = find_province(province_id);
    return province == NULL ? NULL : &province->value;
}

size_t weather_location_city_count(weather_province_id_t province_id)
{
    const province_record_t *province = find_province(province_id);
    return province == NULL ? 0U : province->city_count;
}

const weather_city_t *weather_location_city_at(
    weather_province_id_t province_id, size_t index)
{
    const province_record_t *province = find_province(province_id);
    if (province == NULL || index >= province->city_count) {
        return NULL;
    }
    return &k_cities[(size_t)province->first_city + index];
}

const weather_city_t *weather_location_city_by_id(
    weather_city_id_t city_id)
{
    size_t low = 0U;
    size_t high = WEATHER_LOCATION_CITY_COUNT;
    while (low < high) {
        const size_t middle = low + (high - low) / 2U;
        if (k_cities[middle].id < city_id) {
            low = middle + 1U;
        } else {
            high = middle;
        }
    }
    if (low >= WEATHER_LOCATION_CITY_COUNT ||
        k_cities[low].id != city_id) {
        return NULL;
    }
    return &k_cities[low];
}

bool weather_location_city_belongs_to(
    weather_province_id_t province_id, weather_city_id_t city_id)
{
    const weather_city_t *city = weather_location_city_by_id(city_id);
    return find_province(province_id) != NULL && city != NULL &&
           city->province_id == province_id;
}

bool weather_location_selection_is_valid(
    weather_province_id_t province_id, weather_city_id_t city_id)
{
    return weather_location_city_belongs_to(province_id, city_id);
}
